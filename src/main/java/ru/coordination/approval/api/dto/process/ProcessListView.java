package ru.coordination.approval.api.dto.process;

/**
 * Представление списка процессов — параметр {@code view} у {@code GET /api/v1/processes}.
 *
 * <p>Появился потому, что список отдавал {@link ProcessDto}: полный агрегат на каждую строку
 * страницы (этапы → итерации → участники). Замеры ({@code doc/LOAD_TESTING.md} §5.3) показали цену:
 * 31 запрос к БД на страницу из 20 строк и ~31 запрос на строку до пакетной подгрузки, тогда как
 * тот же список в кратком виде стоит 1–2 запроса. Требование к производительности здесь не
 * эстетическое: список — самый частый запрос UI, и именно он определял p95/p99 профиля чтения.
 *
 * <p>Спецификация {@code 07_api_contract.md} §12.2 для этого эндпоинта описывает как раз краткое
 * представление (идентификатор, ссылка на сущность, тип, статус, инициатор, даты), поэтому
 * {@link #SUMMARY} — движение к контракту, а {@link #FULL} — сохранение прежнего поведения для тех
 * клиентов, кому нужны этапы и участники прямо в списке.
 */
public enum ProcessListView {

    /** Полный {@link ProcessDto} (поведение по умолчанию): этапы, итерации, участники. */
    FULL,

    /** Краткая карточка {@link ProcessSummaryDto}: без этапов и участников, но с текущим этапом. */
    SUMMARY;

    /**
     * Разбирает значение параметра {@code view} без учёта регистра.
     *
     * <p>Явный разбор, а не автоматическое преобразование Spring: то требует точного совпадения с
     * именем константы, поэтому {@code view=summary} (как пишут в запросах) дало бы {@code 400}, а
     * {@code view=SUMMARY} — работало. Такое поведение выглядит как случайная ошибка клиента.
     *
     * @throws IllegalArgumentException если значение не поддерживается; обработчик отдаёт
     *                                  {@code 400 BAD_REQUEST} — опечатка не должна молча
     *                                  превращаться в другое представление ответа
     */
    public static ProcessListView parse(String raw) {
        for (ProcessListView candidate : values()) {
            if (candidate.name().equalsIgnoreCase(raw)) {
                return candidate;
            }
        }
        throw new IllegalArgumentException(
                "Unsupported view: '%s' (expected full or summary)".formatted(raw));
    }
}

package ru.coordination.approval.domain.audit;

/**
 * Тип действия над конфигурацией state machine. См. 03_domain_model.md §9.2, 08_db_schema.md §21.2.
 *
 * <p>Полный жизненный цикл карты: те же шаги, что у {@code Template} (ADR-023), но
 * {@code ConfigAuditEvent} пока никем не пишется — аудит публикации карт ведётся только
 * значениями этих констант в БД, если запись появится извне.
 */
public enum ConfigAuditAction {

    /** Карта создана (черновик). */
    CREATED,

    /** Карта изменена в рамках черновика (до публикации). */
    UPDATED,

    /** Карта опубликована и стала исполняемой для процессов. */
    PUBLISHED,

    /** Карта снята с публикации; начатые процессы продолжают работать по ней. */
    DEPRECATED,

    /** Карта архивирована — терминальный статус версии. */
    ARCHIVED
}

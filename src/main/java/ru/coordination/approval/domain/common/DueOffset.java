package ru.coordination.approval.domain.common;

/**
 * Смещение срока для дополнительных согласующих. См. 03_domain_model.md §6.5, §7.7.
 *
 * <p>Задаётся в шаблоне слота ({@code slot_template.due_offset}, {@code 08_db_schema.md} §6.4) и
 * переносится в конкретного согласующего ({@code additional_approver.due_offset}, §10.1).
 * Смещение отрицательное и отсчитывается от срока основного участника: чем позже согласующий в
 * иерархии, тем короче его срок (значения — {@code 01_glossary.md} §5.8).
 */
public enum DueOffset {

    /** Без сокращения срока: {@code dueAt} доп. согласующего равен сроку основного участника. */
    H0,

    /** Срок раньше на 3 часа — «−3 часа» от срока основного участника. */
    H3,

    /** Срок раньше на 8 часов — «−8 часов» от срока основного участника. */
    H8
}

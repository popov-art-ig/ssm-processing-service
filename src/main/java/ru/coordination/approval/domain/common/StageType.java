package ru.coordination.approval.domain.common;

/**
 * Тип этапа маршрута. См. 03_domain_model.md §6.4 (StageTemplate), §7.3 (StageInstance).
 *
 * <p>Набор значений закреплён check-констрейнтом в БД ({@code 08_db_schema.md} §6.3, §8.1),
 * парного справочника-реестра для типа этапа нет — в отличие от {@code status}.
 */
public enum StageType {

    /**
     * Согласование: основной сценарий этапа — участники выносят решение, агрегация решений
     * определяет переход этапа. Во всех сценариях {@code 12_test_scenarios.md} используется
     * именно это значение.
     */
    APPROVAL,

    /**
     * Подписание. Значение объявлено схемой и API, но отдельных правил (свой набор ролей,
     * особый порядок завершения) ни {@code 03_domain_model.md}, ни реестр guards/actions не
     * задают — поведение совпадает с {@link #APPROVAL}.
     */
    SIGNING,

    /**
     * Ознакомление (визирование). Как и {@link #SIGNING}, отдельной логики в спецификации нет —
     * различие только декларативное, в поле {@code stage_type}.
     */
    ENDORSEMENT
}

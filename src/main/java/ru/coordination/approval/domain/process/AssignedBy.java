package ru.coordination.approval.domain.process;

/**
 * Кем назначен дополнительный согласующий. См. 03_domain_model.md §7.7.
 *
 * <p>Помимо источника назначения значение задаёт форму иерархии: check-констрейнт БД
 * ({@code 08_db_schema.md} §10.1) требует, чтобы {@link #ADDITIONAL_APPROVER} был единственным
 * значением с заполненным {@code parent_additional_approver_id}, а остальные — с пустым.
 */
public enum AssignedBy {

    /** Доп. согласующий предусмотрен шаблоном (слот типа {@code ADDITIONAL_APPROVER}). */
    TEMPLATE,

    /** Добавлен инициатором процесса вручную перед стартом или во время согласования. */
    INITIATOR,

    /** Добавлен основным согласующим (участником) по ходу работы над задачей. */
    PARTICIPANT,

    /** Создан другим доп. согласующим — только этот случай даёт непустого родителя (уровень &gt; 1). */
    ADDITIONAL_APPROVER
}

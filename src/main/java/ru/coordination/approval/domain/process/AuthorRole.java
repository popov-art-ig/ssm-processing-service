package ru.coordination.approval.domain.process;

/**
 * Роль автора замечания/комментария. См. 03_domain_model.md §7.9, §7.10.
 * Примечание: для {@code Comment} доменная модель не перечисляет конкретные значения —
 * повторно используется тот же набор, что и для {@code Remark}, до уточнения в следующих фазах.
 *
 * <p>На практике набор пока вырожден: и замечание, и комментарий создаются с ролью
 * {@link #APPROVER} — {@code RemarkService.createRemark} и {@code RecordCommentAction} жёстко
 * подставляют это значение (для комментария роль вообще всегда одна).
 */
public enum AuthorRole {

    /**
     * Автор — основной согласующий/подписант этапа (роль {@code ParticipantRole.APPROVER} или
     * {@code SIGNER}). Единственное значение, которое проставляется кодом.
     */
    APPROVER,

    /**
     * Автор — дополнительный согласующий. Значение объявлено для замечаний доп. согласующих
     * (PHASE-10), которые в текущей реализации не создаются.
     */
    ADDITIONAL_APPROVER
}
